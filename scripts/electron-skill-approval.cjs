const assert = require('node:assert/strict')
const { mkdtemp, rm } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { expect } = require('playwright/test')

async function verifySkillApproval(launchApplication) {
  const root = await mkdtemp(join(tmpdir(), 'anas-skill-approval-e2e-'))
  let application
  try {
    application = await launchApplication(root)
    const page = await application.firstWindow()
    await page.waitForSelector('[data-agent-composer-input]')
    await page.evaluate(() => globalThis.gale.config.updateSettings({ language: 'en' }))
    await page.reload()
    await page.waitForSelector('[data-agent-composer-input]')
    await page.locator('.sidebar-settings').click()
    await page.locator('.app-menu-item').first().click()
    await page.locator('[data-settings-tab="skills"]').click()
    const global = page.getByRole('checkbox', { name: 'Auto-approve all Skill scripts', exact: true })
    await expect(global).not.toBeChecked()
    await page.locator('.settings-skill-tree-root').filter({ hasText: 'System' }).click()
    await page.locator('.settings-skill-tree-select').filter({ hasText: /^config$/ }).click()
    const individual = page.getByRole('checkbox', { name: 'Auto-approve scripts', exact: true })
    await expect(individual).not.toBeChecked()
    const skillRow = page.locator('.settings-skill-tree-row').filter({ has: page.locator('.settings-skill-tree-select').filter({ hasText: /^config$/ }) })
    const skillName = skillRow.locator('.settings-skill-tree-label')
    const nameColor = () => skillName.evaluate(element => globalThis.getComputedStyle(element).color)
    const normalColor = await nameColor()
    const current = () => page.evaluate(async () => {
      const snapshot = await globalThis.gale.skills.get()
      return { global: snapshot.scriptAutoApprove, individual: snapshot.skills.find(skill => skill.id === 'system:config').scriptAutoApprove }
    })
    await global.click()
    await expect.poll(current).toEqual({ global: true, individual: false })
    await expect(global).toBeChecked()
    await expect.poll(nameColor).toBe(normalColor)
    await expect(individual).not.toBeChecked()
    await expect(page.getByText('Global script auto-approval is active.', { exact: false })).toBeVisible()
    await individual.click()
    await expect.poll(current).toEqual({ global: true, individual: true })
    await expect(individual).toBeChecked()
    await expect.poll(nameColor).not.toBe(normalColor)
    const exemptColor = await nameColor()
    await global.click()
    await expect.poll(current).toEqual({ global: false, individual: true })
    await expect(global).not.toBeChecked()
    await expect.poll(nameColor).toBe(exemptColor)
    await expect(skillRow.getByRole('img')).toHaveCount(0)
    const viewer = page.locator('.settings-skill-viewer')
    await expect(viewer.getByRole('button', { name: 'Open', exact: true })).toHaveCount(0)
    const path = await page.evaluate(async () => (await globalThis.gale.skills.get()).skills.find(skill => skill.id === 'system:config').dirPath)
    const location = viewer.getByRole('button', { name: path, exact: true })
    await expect(location).toBeVisible()
    const shortcut = viewer.getByText('/config', { exact: true })
    assert.ok((await location.boundingBox()).y < (await shortcut.boundingBox()).y, 'Skill location belongs above its shortcut.')
    assert.ok((await global.boundingBox()).x > (await page.locator('.settings-page-title').boundingBox()).x, 'Global control belongs to the right of the page title.')
    await application.evaluate(({ ipcMain }) => {
      ipcMain.removeHandler('files:showItemInFolder')
      ipcMain.handle('files:showItemInFolder', (_event, path) => { globalThis.__revealedSkill = path })
    })
    await location.click()
    await expect.poll(() => application.evaluate(() => globalThis.__revealedSkill)).toBe(path)
    if (process.env.ANAS_E2E_SKILL_APPROVAL_SCREENSHOT) await page.screenshot({ path: process.env.ANAS_E2E_SKILL_APPROVAL_SCREENSHOT })
    await page.reload()
    await page.waitForSelector('[data-agent-composer-input]')
    await expect.poll(current).toEqual({ global: false, individual: true })
    console.log('Skill approval E2E passed: default-off controls, independent persistence, global status, requested layout, and location reveal.')
  } finally {
    await application?.close().catch(() => undefined)
    assert.ok(root.startsWith(join(tmpdir(), 'anas-skill-approval-e2e-')))
    await rm(root, { recursive: true, force: true })
  }
}

module.exports = { verifySkillApproval }
